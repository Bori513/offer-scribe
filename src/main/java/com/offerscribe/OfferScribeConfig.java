package com.offerscribe;

import java.awt.event.KeyEvent;
import net.runelite.client.config.*;

@ConfigGroup("offerscribe")
public interface OfferScribeConfig extends Config {
    @ConfigItem(keyName="syncEnabled", name="Dashboard synchronization", description="Send the disclosed GE fill fields to your configured Offer Scribe dashboard", warning="This feature submits your IP address to a 3rd-party server not controlled or verified by RuneLite developers", position=1)
    default boolean syncEnabled() { return false; }
    @ConfigItem(keyName="dashboardUrl", name="Dashboard API URL", description="HTTPS API base ending in /api/v1; plain HTTP is accepted only for localhost", position=2)
    default String dashboardUrl() { return ""; }
    @ConfigItem(keyName="pairingCode", name="Pairing code", description="Single-use code generated by the dashboard; cleared after successful pairing", position=3)
    default String pairingCode() { return ""; }
    @ConfigItem(keyName="marketDataEnabled", name="External market data", description="Fetch selected item IDs and public high/low prices from the OSRS Wiki price API. Your IP address is visible to that service.", warning="This feature submits your IP address to a 3rd-party server not controlled or verified by RuneLite developers", position=4)
    default boolean marketDataEnabled() { return false; }
    @ConfigItem(keyName="diagnosticsEnabled", name="Diagnostic reporting", description="Not implemented; remains off", hidden=true, position=5)
    default boolean diagnosticsEnabled() { return false; }
    @Range(min=100_000, max=2_000_000_000)
    @ConfigItem(keyName="recommendationBudget", name="Legacy budget cap", description="Retained for settings compatibility; recommendations now use the visible coin stack in your inventory", hidden=true, position=6)
    default int recommendationBudget() { return 10_000_000; }
    @ConfigItem(keyName="includeMembersItems", name="Include members items", description="Include members-only items in opportunity recommendations", position=7)
    default boolean includeMembersItems() { return false; }
    @ConfigItem(keyName="quickSetKeybind", name="Legacy quick-set key", description="Retained for settings compatibility; values are now displayed for manual entry", hidden=true, position=8)
    default Keybind quickSetKeybind() { return new Keybind(KeyEvent.VK_E, 0); }
}
